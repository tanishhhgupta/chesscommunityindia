import { EngineStanding, Pairing, Player, Tournament } from '../types';

export function printTournamentDocument(title: string): void {
  const originalTitle = document.title;
  document.title = `${title} - ChessPair`;
  window.print();
  document.title = originalTitle;
}

export function exportPairingsText(
  tournament: Tournament,
  roundNumber: number,
  pairings: (Pairing & { whitePlayer?: Player; blackPlayer?: Player })[]
): string {
  const header = `=========================================================\n${tournament.name}\nRound ${roundNumber} Pairings | Time Control: ${tournament.timeControlString}\nChief Arbiter: ${tournament.chiefArbiter || 'Unassigned'}\n=========================================================\n`;
  const sub = `Brd  White Player                   Rating  Res  Black Player                   Rating\n-----------------------------------------------------------------------------------------\n`;

  const rows = pairings.map((p) => {
    const brd = String(p.boardNumber).padStart(2, ' ');
    if (p.isBye) {
      const pName = (p.whitePlayer?.name || 'Player').padEnd(28, ' ');
      const pRat = String(p.whitePlayer?.rating || '-').padStart(5, ' ');
      return `${brd}   ${pName}  ${pRat}   BYE  (1.0 Full-point bye)`;
    }
    const wName = (p.whitePlayer?.name || 'TBD').padEnd(28, ' ');
    const wRat = String(p.whitePlayer?.rating || '-').padStart(5, ' ');
    const bName = (p.blackPlayer?.name || 'TBD').padEnd(28, ' ');
    const bRat = String(p.blackPlayer?.rating || '-').padStart(5, ' ');
    const res = (p.result === 'UNPLAYED' ? ' - ' : p.result).padStart(4, ' ');

    return `${brd}   ${wName}  ${wRat}  ${res}  ${bName}  ${bRat}`;
  });

  return `${header}${sub}${rows.join('\n')}\n-----------------------------------------------------------------------------------------\n`;
}

export function exportStandingsText(tournament: Tournament, standings: EngineStanding[]): string {
  const header = `=========================================================================================\n${tournament.name}\nOfficial Standings | Format: ${tournament.format} | Rounds: ${tournament.roundsCount}\nGenerated by ChessPair Tournament Engine\n=========================================================================================\n`;
  const sub = `Rk  Title  Player Name                    Rating  Pts   BH-1   BH-T    SB    Wins  Blk\n-----------------------------------------------------------------------------------------\n`;

  const rows = standings.map((s) => {
    const rk = String(s.rank).padStart(2, ' ');
    const title = (s.title && s.title !== 'None' ? s.title : '').padEnd(5, ' ');
    const name = s.playerName.padEnd(28, ' ');
    const rat = String(s.rating).padStart(5, ' ');
    const pts = s.score.toFixed(1).padStart(4, ' ');
    const bh1 = s.buchholzCut1.toFixed(1).padStart(5, ' ');
    const bht = s.buchholzTotal.toFixed(1).padStart(5, ' ');
    const sb = s.sonnebornBerger.toFixed(2).padStart(6, ' ');
    const wins = String(s.wins).padStart(4, ' ');
    const blk = String(s.blacks).padStart(4, ' ');

    return `${rk}  ${title}  ${name}  ${rat}  ${pts}  ${bh1}  ${bht}  ${sb}  ${wins}  ${blk}`;
  });

  return `${header}${sub}${rows.join('\n')}\n-----------------------------------------------------------------------------------------\n`;
}

export function exportStandingsCsv(params: {
  tournament: Tournament;
  standings: EngineStanding[];
  players?: Player[];
  rounds?: any[];
  pairings?: Pairing[];
}): string {
  const { tournament, standings } = params;
  const headers = ['Rank', 'Title', 'Player Name', 'Rating', 'Points', 'Buchholz Cut-1', 'Buchholz Total', 'Sonneborn-Berger', 'Wins', 'Blacks'];
  const lines = [
    `# Tournament: ${tournament.name}`,
    `# Format: ${tournament.format}`,
    headers.join(','),
  ];

  for (const s of standings) {
    const row = [
      s.rank,
      `"${s.title || ''}"`,
      `"${s.playerName.replace(/"/g, '""')}"`,
      s.rating,
      s.score,
      s.buchholzCut1.toFixed(1),
      s.buchholzTotal.toFixed(1),
      s.sonnebornBerger.toFixed(2),
      s.wins,
      s.blacks,
    ];
    lines.push(row.join(','));
  }

  return lines.join('\n');
}

export function exportPairingsCsv(params: {
  tournament: Tournament;
  round: any;
  pairings: Pairing[];
  players?: Player[];
}): string {
  const { tournament, round, pairings, players = [] } = params;
  const pMap = new Map(players.map((p) => [p.id, p]));

  const headers = ['Board', 'White Player', 'White Rating', 'Result', 'Black Player', 'Black Rating', 'Is Bye'];
  const lines = [
    `# Tournament: ${tournament.name}`,
    `# Round: ${round?.roundNumber || 1}`,
    headers.join(','),
  ];

  for (const p of pairings) {
    const white = p.whitePlayerId ? pMap.get(p.whitePlayerId) : undefined;
    const black = p.blackPlayerId ? pMap.get(p.blackPlayerId) : undefined;

    const row = [
      p.boardNumber,
      `"${(white?.name || p.whitePlayerId || 'TBD').replace(/"/g, '""')}"`,
      white?.rating || '',
      `"${p.result || 'UNPLAYED'}"`,
      p.isBye ? '"BYE"' : `"${(black?.name || p.blackPlayerId || 'TBD').replace(/"/g, '""')}"`,
      black?.rating || '',
      p.isBye ? 'true' : 'false',
    ];
    lines.push(row.join(','));
  }

  return lines.join('\n');
}

export function exportPlayersCsv(players: Player[]): string {
  const headers = ['ID', 'Name', 'Rating', 'Title', 'Federation', 'Club', 'FIDE ID', 'Email', 'Phone', 'Is Active'];
  const lines = [headers.join(',')];

  for (const p of players) {
    const row = [
      p.id,
      `"${p.name.replace(/"/g, '""')}"`,
      p.rating,
      p.title || 'None',
      p.federation || 'IND',
      `"${(p.club || '').replace(/"/g, '""')}"`,
      p.fideId || '',
      `"${p.email || ''}"`,
      `"${p.phone || ''}"`,
      p.isActive ? 'true' : 'false',
    ];
    lines.push(row.join(','));
  }

  return lines.join('\n');
}
